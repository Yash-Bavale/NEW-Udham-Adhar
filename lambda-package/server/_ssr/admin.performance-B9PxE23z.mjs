function getCleanActionBadge(raw) {
  if (!raw) return "ACTIVITY";
  let s = raw.replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi, "").replace(/moved to\s*$/i, "").replace(/moved to\s+[0-9a-f]{6,}/i, "").trim();
  if (!s || /^moved to/i.test(s) || /^[0-9a-f\-]+$/i.test(s)) {
    return "STAGE UPDATED";
  }
  return s.slice(0, 22).toUpperCase();
}
function getCleanActionDetails(raw) {
  if (!raw) return "Operational verification logged";
  let s = raw.replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi, "").replace(/moved to\s*$/i, "Order stage updated").replace(/moved to\s+[0-9a-f]{6,}/i, "Order stage updated").trim();
  if (!s || /^moved to/i.test(s) || /^[0-9a-f\-]+$/i.test(s)) {
    return "Order fulfillment stage updated";
  }
  return s;
}
