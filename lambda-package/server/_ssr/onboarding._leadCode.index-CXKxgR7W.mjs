const SITE_SUFFIX = /--[a-z0-9]{1,8}$/;
function baseServiceCode(code) {
  if (!code) return "";
  return code.replace(SITE_SUFFIX, "");
}
function isService(code, base) {
  return baseServiceCode(code) === base;
}
