async function loadAndTriggerCashfreeCheckout(paymentSessionId, isProd) {
  const scriptUrl = isProd ? "https://sdk.cashfree.com/js/v3/cashfree.js" : "https://sdk.cashfree.com/js/v3/cashfree.js";
  if (!window.Cashfree) {
    await new Promise((resolve, reject) => {
      const script = document.createElement("script");
      script.src = scriptUrl;
      script.onload = () => resolve();
      script.onerror = () => reject(new Error("Failed to load Cashfree Payment SDK"));
      document.head.appendChild(script);
    });
  }
  if (window.Cashfree) {
    const cashfree = window.Cashfree({
      mode: isProd ? "production" : "sandbox"
    });
    cashfree.checkout({
      paymentSessionId,
      redirectTarget: "_self"
    });
  } else {
    throw new Error("Cashfree SDK failed to initialize.");
  }
}
